package com.otokana.core

/** A writing system. */
enum class Script(val id: String) { Hiragana("hiragana"), Katakana("katakana") }

/** A group of the table, in the order decks are built from. */
enum class Group { Mono, Dia, Di, DiDia }

/** One kana with its accepted romaji; [aliases] includes [romaji]. */
data class Entry(
    val romaji: String,
    val hiragana: String,
    val katakana: String,
    val aliases: List<String>,
    val group: Group,
) {
    fun kana(s: Script) = if (s == Script.Katakana) katakana else hiragana
}

private fun e(r: String, h: String, k: String, g: Group, vararg extra: String) =
    Entry(r, h, k, listOf(r) + extra, g)

